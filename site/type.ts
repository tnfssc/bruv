export function headline(value: string, width: number, compact: boolean) {
  const font = compact ? small : glyphs,
    gw = compact ? 3 : 5,
    gh = compact ? 5 : 7;
  const words = value.toUpperCase().split(" ");
  const lines: string[] = [];
  let line = "";
  for (const word of words) {
    if (line && (line.length + word.length + 1) * (gw + 1) - 1 > width) {
      lines.push(line);
      line = "";
    }
    line += (line ? " " : "") + word;
  }
  if (line) lines.push(line);
  return lines.flatMap((line, i) => {
    const pixels = Array.from({ length: gh + 1 }, (_, y) =>
      [...line].map((c) => font[c]?.[y] || "0".repeat(gw)).join("0"),
    );
    const result: string[] = [];
    for (let y = 0; y < gh; y += 2)
      result.push(
        [...pixels[y]]
          .map((v, x) => (v === "1" ? (pixels[y + 1][x] === "1" ? "█" : "▀") : pixels[y + 1][x] === "1" ? "▄" : " "))
          .join(""),
      );
    return i < lines.length - 1 ? [...result, ""] : result;
  });
}

